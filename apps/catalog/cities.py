    slug: str
    name: str
    where: str
    intro: str
    delivery: str
    install: str

    @property
    def h1(self):
        return f'Кондиционеры {self.where}: продажа и установка'

    @property
    def title(self):
        return f'Кондиционеры {self.where} — купить с установкой | SplitHome'

    @property
    def description(self):
        return (f'Кондиционеры и сплит-системы {self.where} с доставкой и монтажом. '
                f'Модели в наличии на складе в Крыму, установка с гарантией. SplitHome.')


